/**
 * The evidence pack: the open questions (`open-items.ts`) and, for each, one
 * small evidence window that the AI analyst may read. Windows keep the
 * original line numbers so every answer can cite `path:line`. Secrets are
 * redacted line by line and the pack stays inside a fixed size limit.
 * Repository content is untrusted data.
 */
import type { AnalysisResult } from '../analyser.js';
import { listDockerfileCandidates, TREE_PATHS, type FileTree } from '../detectors.js';
import { MANAGED_DATABASE_ENV_VARS, MANAGED_STORAGE_ENV_VARS } from '../env-classification.js';
import { redactSecrets } from '../redact.js';
import { collectOpenItems, type BlockerItem, type OpenItem } from './open-items.js';

/** The whole pack, in characters of window content. */
export const MAX_PACK_CHARS = 40_000;
/** The windows of one question, in characters. */
export const MAX_QUESTION_CHARS = 8_000;
/** The shared start-path window (Dockerfile and start scripts), in characters. */
export const MAX_START_PATH_CHARS = 8_000;
/** Lines shown before and after each search hit. */
export const WINDOW_RADIUS = 8;
/** Search hits shown per question. */
const MAX_HITS = 8;
/** Repository paths listed (names only) so the model knows what exists. */
export const MAX_LISTED_PATHS = 150;

export interface PackFile {
  readonly path: string;
  /** The line number of `lines[0]`. */
  readonly start: number;
  /** Redacted lines from `start` on. */
  readonly lines: readonly string[];
}

export type Question = OpenItem & {
  readonly id: string;
  readonly windows: readonly PackFile[];
};

export interface EvidencePack {
  readonly questions: readonly Question[];
  /** The selected Dockerfile and the scripts it starts: shared by every question. */
  readonly startPath: readonly PackFile[];
  /** The environment variables Deployz sets for this repository (see `bindingContractOf`). */
  readonly bindingContract: BindingContract;
  readonly paths: readonly string[];
  readonly totalPaths: number;
}

/**
 * The environment variables Deployz sets, from the deterministic env-var
 * model and bindings: what it sets for the resources the rules found, and
 * the standard names it sets when it provisions a resource.
 */
export interface BindingContract {
  readonly always: readonly string[];
  /** Names the rules classified as set or generated by Deployz for this repository. */
  readonly forThisRepository: readonly string[];
  readonly whenDatabase: readonly string[];
  readonly whenRedis: readonly string[];
  readonly whenStorage: readonly string[];
}

const REDIS_STANDARD_NAMES = ['REDIS_URL', 'REDIS_HOST', 'REDIS_PORT'] as const;

function bindingNames(meta: Record<string, unknown>, resource: string): string[] {
  const raw = meta['infrastructureBindings'];
  if (!Array.isArray(raw)) return [];
  return raw.flatMap((entry) => {
    const record = entry as { resource?: unknown; applicationVariable?: unknown };
    return record.resource === resource && typeof record.applicationVariable === 'string' ? [record.applicationVariable] : [];
  });
}

export function bindingContractOf(analysis: AnalysisResult): BindingContract {
  const meta = analysis.metadata;
  const model = Array.isArray(meta['envVarModel']) ? (meta['envVarModel'] as Array<Record<string, unknown>>) : [];
  const provided = model
    .filter((entry) => entry['classification'] === 'deployz_managed' || entry['classification'] === 'deployz_generated')
    .flatMap((entry) => (typeof entry['key'] === 'string' ? [entry['key']] : []));
  const unique = (names: readonly string[]) => [...new Set(names)].sort();
  return {
    always: ['PORT', 'HOSTNAME'],
    forThisRepository: unique(provided),
    whenDatabase: unique([...MANAGED_DATABASE_ENV_VARS, ...bindingNames(meta, 'postgres')]),
    whenRedis: unique([...REDIS_STANDARD_NAMES, ...bindingNames(meta, 'redis')]),
    whenStorage: unique([...MANAGED_STORAGE_ENV_VARS, ...bindingNames(meta, 's3')]),
  };
}

const ENV_SAMPLE = /^\.env\.(?:example|sample|template|dist)$/i;
const SECRET_FILE = /\.(?:pem|key|p12|pfx|jks|keystore)$|^id_[a-z0-9]+$|^credentials(?:\.\w+)?$|^\.npmrc$|^\.pypirc$/i;
const LOCKFILE = /(?:^|\/)(?:pnpm-lock\.yaml|yarn\.lock|bun\.lockb?|package-lock\.json|composer\.lock|Gemfile\.lock|poetry\.lock|uv\.lock|Cargo\.lock|mix\.lock|go\.sum|packages\.lock\.json)$/i;
const PRIVATE_KEY_BLOCK = /-----BEGIN [A-Z ]*PRIVATE KEY-----/;
const VENDORED = /(?:^|\/)(?:node_modules|vendor|dist|build|\.git)\//;
const NOT_PRODUCTION = /(?:^|\/)(?:tests?|specs?|__tests__|__mocks__|examples?|samples?|docs?|e2e|cypress|fixtures?|testdata|benchmarks?|load-?tests?|node_modules|vendor|\.[^/]+)\//i;
/** Binary files, and the built browser bundles a server serves as static files. */
const BINARY = /\.(?:png|jpe?g|gif|ico|svg|woff2?|ttf|eot|pdf|zip|gz|tar|jar|wasm|mp4|webp|map|min\.js)$|(?:^|\/)(?:public|static|assets|wwwroot)\/(?:.*\/)?[^/]+\.js$/i;

/** A path the pack never includes: secrets, real env files, lockfiles, vendored code. */
export function isExcludedPath(path: string): boolean {
  const base = path.split('/').pop() ?? path;
  if ((base === '.env' || base.startsWith('.env.')) && !ENV_SAMPLE.test(base)) return true;
  return SECRET_FILE.test(base) || LOCKFILE.test(path) || VENDORED.test(path);
}

const TEST_FILE = /\.(?:test|spec|stories|e2e|cy)\.[\w]+$|(?:^|\/)(?:conftest\.py|test_[\w-]+\.py|[\w-]+_test\.(?:py|go|rb))$/i;

/** The root README: evidence for the repository kind question only (what the repository is). */
export const ROOT_README = /^README(?:\.(?:md|markdown|rst|txt|adoc))?$/i;
/** The part of the root README that the repository kind question shows, in characters. */
export const MAX_README_CHARS = 2_000;

/** A file of the production app: not excluded, not a test, example or document, not binary. Scripts and `bin/` count. */
export function isProductionFile(path: string): boolean {
  return !isExcludedPath(path) && !NOT_PRODUCTION.test(path) && !BINARY.test(path) && !TEST_FILE.test(path) && !ROOT_README.test(path);
}

/** `KEY=value` → `KEY=` per line, so an env sample shows names only and keeps its line numbers. */
function stripEnvValue(line: string): string {
  return line.replace(/^(\s*(?:export\s+)?[A-Za-z_][A-Za-z0-9_]*\s*[=:]).*$/, '$1');
}

/** Lines `from`..`to` (1-based, inclusive) of a file, redacted, inside `budget` characters; null for a file with a private key. */
export function window(path: string, content: string, from: number, to: number, budget: number): PackFile | null {
  if (PRIVATE_KEY_BLOCK.test(content)) return null;
  const envSample = ENV_SAMPLE.test(path.split('/').pop() ?? path);
  const all = content.split(/\r?\n/);
  const lines: string[] = [];
  let used = 0;
  for (let index = Math.max(1, from); index <= Math.min(to, all.length); index += 1) {
    const raw = all[index - 1]!;
    const line = redactSecrets(envSample ? stripEnvValue(raw) : raw).slice(0, 400);
    if (used + line.length + 1 > budget) break;
    lines.push(line);
    used += line.length + 1;
  }
  return lines.length === 0 ? null : { path, start: Math.max(1, from), lines };
}

function size(file: PackFile): number {
  return file.lines.reduce((sum, line) => sum + line.length + 1, 0);
}

/** The files the Dockerfile names as its entrypoint or start script. */
export function startScripts(dockerfile: string | undefined, tree: FileTree): string[] {
  if (dockerfile === undefined) return [];
  const content = tree[dockerfile] ?? '';
  const scripts: string[] = [];
  for (const match of content.matchAll(/[\w./-]+\.(?:sh|bash|py|rb|exs|js|mjs|cjs|ts|php)\b/g)) {
    const name = match[0].replace(/^\.?\//, '');
    const found = Object.keys(tree).find((path) => path === name || path.endsWith(`/${name}`));
    if (found !== undefined) scripts.push(found);
  }
  return scripts;
}

function escape(text: string): string {
  return text.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

/**
 * A line that says what a datastore server is: its role (a database, a broker, a search engine) or the
 * default client port of a database, cache or broker protocol (`port 6379`, `DEF_PGPORT 5432`).
 */
export const DATASTORE_ROLE =
  /\b(?:database (?:server|management system)|relational databases?|datastore|data store|key[- ]value (?:store|database)|search engine|vector (?:database|store|search engine)|(?:message|messaging|streaming)(?: and streaming)? broker|event streaming|object stor(?:e|age) server|S3 object store|distributed file system|time[- ]series database)\b|port\b\D{0,30}\b(?:1883|8883|5671|5672|9092|4222|3306|5432|6379|27017|9042|7687|26257)\b/i;

/** What each fact question searches the production files for. */
const FACT_SEARCH: Record<string, RegExp> = {
  port: /\bPORT\b|\.listen\(|\blisten\b|server\.port|--port\b|\bbind\b.*:\d{2,5}|ASPNETCORE_URLS|EXPOSE/,
  startCommand: /"(?:start|serve|prod|production|start:prod)"\s*:|^\s*web:|\bexec\b/,
  healthPath: /health|ready|alive|\bping\b|\/status\b|Map(?:Get|HealthChecks)|@(?:Get|RequestMapping)\(|\.get\(\s*["']\/["']|urlpatterns|\broutes?\b/i,
  migration: /migrat|db:prepare|db\s+push|alembic|flyway|liquibase|ecto\.migrate|syncdb|schema:update|ensure\w*(?:schema|tables?)\b|CREATE TABLE|\.Install\w*\(/i,
  databaseVariable: /(?<![a-z0-9])(?:db|database|postgres|pg|sql|dsn|datasource|connection)/i,
  // A server entrypoint: what an application of this repository would start; or what a datastore server is.
  repositoryKind: new RegExp(`${/\.listen\(|uvicorn|gunicorn|FastAPI\(|Flask\(|createServer|ListenAndServe|HttpServer::new|axum::serve|runserver|"start"\s*:|^\s*web:/.source}|${DATASTORE_ROLE.source}`, 'i'),
};

/** A line that reads the environment: the switches a blocker or a fact most often turns on. */
const READS_ENV = /process\.env|getenv|environ|ENV\[|ENV\.fetch|System\.get_?env|Environment\.GetEnvironmentVariable|os\.Getenv|\benv\(|\$\{\w/;
/** A quoted health-like route: the decisive line of a health path. */
const HEALTH_ROUTE = /["'`]\/(?:api\/)?(?:health\w*|healthz|readyz?|livez?|alive|ping|status|up)\b/i;
/** Files on or near the start path: entrypoints, boot code, the server's main file. */
const START_FILE = /(?:^|\/)(?:[^/]*entrypoint[^/]*|start[^/]*|boot[^/]*|run[^/]*\.sh|[^/]*\.sh|Program\.cs|Startup\.cs|main\.\w+|server\.\w+|app\.\w+|application\.\w+|index\.\w+|config\/initializers\/[^/]+|release\.ex|rel\/[^/]+)$/i;

/** The rank of a hit, best first: what makes a line decisive for the question. */
type Rank = (path: string, line: string) => number;

/** Dependency manifests: they name packages, not routes, ports or boot steps, so they rank last for a fact. */
const MANIFEST = /(?:^|\/)(?:package\.json|composer\.json|pom\.xml|build\.gradle(?:\.kts)?|[^/]+\.csproj|mix\.exs|go\.mod|Gemfile|pyproject\.toml|Cargo\.toml)$/i;
const BROWSER_FILE = /\.(?:tsx|jsx|vue|svelte)$|(?:^|\/)(?:frontend|client|web|ui)\/src\//i;
const last = (rank: Rank): Rank => (path, line) => (MANIFEST.test(path) ? 3 : rank(path, line));

const RANKS: Record<string, Rank> = {
  blocker: (_path, line) => (READS_ENV.test(line) ? 0 : 1),
  port: last((path, line) => (/\bPORT\b/.test(line) && READS_ENV.test(line) ? 0 : START_FILE.test(path) ? 1 : 2)),
  startCommand: last((path) => (START_FILE.test(path) ? 0 : 1)),
  // A browser-side router is not a server route.
  healthPath: last((path, line) => (BROWSER_FILE.test(path) ? 3 : HEALTH_ROUTE.test(line) ? 0 : /health|route|router|urls|controller/i.test(path) ? 1 : 2)),
  // A call that runs the migrations is decisive; an import, a comment or a declaration only names them.
  migration: last((path, line) => (NAMES_ONLY.test(line) ? 3 : START_FILE.test(path) ? 0 : MIGRATION_CALL.test(line) ? 1 : 2)),
  databaseVariable: last((_path, line) => (READS_ENV.test(line) ? 0 : 2)),
  repositoryKind: last((path) => (START_FILE.test(path) ? 0 : 1)),
};
/** A call that runs migrations, or a quoted command or flag name that starts them (`"migrate"`, `'db:migrate'`). */
const MIGRATION_CALL = /(?:\w*migrat\w*|\w*upgrade\w*|ensure\w*(?:schema|tables?)|\w*install\w*)(?:\.\w+)?\s*\(|CREATE TABLE|["'`]-{0,2}[\w:]*migrat\w*["'`]/i;
const NAMES_ONLY = /^\s*(?:using|import|from|require|alias|use|package|namespace|\/\/|#|\*|\/\*|<!--)/;
/** The manifests that publish a package: a library, framework, SDK or CLI is installed from one. */
export const PACKAGE_MANIFEST = /(?:^|\/)(?:package\.json|pyproject\.toml|setup\.(?:py|cfg)|Cargo\.toml|composer\.json|[^/]+\.gemspec)$/i;
/**
 * A manifest line that packages the code for others to install: a build
 * backend, a published entry point (`bin`, `main`, `exports`, a console
 * script), a Rust `[lib]` or `[[bin]]`, a Composer library, a gemspec.
 */
export const PACKAGE_MARKER =
  /build-backend|^\s*\[(?:build-system|project\.scripts|tool\.poetry\.scripts|lib|\[bin\])\]|^\s*requires\s*=\s*\[[^\]]*(?:hatchling|setuptools|poetry|flit|maturin|pdm|scikit-build)|console_scripts|^\s*[\w.-]+\s*=\s*["'][\w.]+:\w+["']|"(?:bin|main|module|exports|types|typings|publishConfig)"\s*:|^\s*"[\w@./-]+"\s*:\s*"(?:\.\/)?bin\/|"type"\s*:\s*"library"|Gem::Specification/;

/** A manifest line that names or packages the project: its packaging marker, its name, or a private flag. */
const PACKAGING = new RegExp(`${PACKAGE_MARKER.source}|${/^\s*\[(?:project|package|tool\.poetry|workspace)\]|"(?:name|private|workspaces)"\s*:/.source}`);

/** Windows of one file in one question, so one long file does not use the whole budget. */
const MAX_WINDOWS_PER_FILE = 3;

/** The search pattern of a blocker: any of its terms as a whole word. */
function blockerSearch(item: BlockerItem): RegExp {
  const terms = item.terms.filter((term) => term.length >= 2).map((term) => (/^[\w-]+$/.test(term) ? `\\b${escape(term)}\\b` : escape(term)));
  return new RegExp(terms.length > 0 ? terms.join('|') : '(?!)', 'i');
}

const DEPLOYMENT_FILE = /(?:^|\/)(?:Dockerfile[^/]*|[^/]*\.dockerfile|(?:docker-)?compose[^/]*\.ya?ml)$/i;
/** Hits kept per rank, so a large repository stays cheap. */
const MAX_CANDIDATES_PER_RANK = 60;

/**
 * Windows around the best hits of `pattern` in the production files, by
 * `rank`, then in file order: the files the reason names first, then source
 * and configuration, then the deployment files (a Compose file repeats the
 * paths the reason names). Windows of one file never overlap.
 */
function hitWindows(tree: FileTree, pattern: RegExp, rank: Rank, first: readonly string[], skip: ReadonlySet<string>, budget: number): PackFile[] {
  const production = Object.keys(tree).filter(isProductionFile).sort();
  const ordered = [...first, ...production.filter((path) => !DEPLOYMENT_FILE.test(path)), ...production.filter((path) => DEPLOYMENT_FILE.test(path))];
  const byRank: Array<Array<{ path: string; number: number }>> = [];
  for (const path of [...new Set(ordered)].filter((entry) => !skip.has(entry))) {
    for (const [index, line] of (tree[path] ?? '').split(/\r?\n/).entries()) {
      if (!pattern.test(line)) continue;
      const level = (byRank[rank(path, line)] ??= []);
      if (level.length < MAX_CANDIDATES_PER_RANK) level.push({ path, number: index + 1 });
    }
  }
  const windows: PackFile[] = [];
  let remaining = budget;
  for (const hit of byRank.flatMap((level) => level ?? [])) {
    if (windows.length >= MAX_HITS || remaining < 300) break;
    const shown = windows.filter((file) => file.path === hit.path);
    if (shown.length >= MAX_WINDOWS_PER_FILE) continue;
    if (shown.some((file) => hit.number >= file.start && hit.number < file.start + file.lines.length)) continue;
    // Start after a window above and stop before a window below, so no line repeats.
    const from = Math.max(hit.number - WINDOW_RADIUS, ...shown.filter((file) => file.start < hit.number).map((file) => file.start + file.lines.length));
    const to = Math.min(hit.number + WINDOW_RADIUS, ...shown.filter((file) => file.start > hit.number).map((file) => file.start - 1));
    const file = window(hit.path, tree[hit.path] ?? '', from, to, Math.min(remaining, 2_000));
    if (file === null) continue;
    windows.push(file);
    remaining -= size(file);
  }
  return windows.sort((a, b) => a.path.localeCompare(b.path) || a.start - b.start);
}

/** Every repository path that a reason names (`path` or `path:line`). */
function namedPaths(text: string, tree: FileTree): string[] {
  return text
    .split(/[\s,;()"'`]+/)
    .map((token) => token.replace(/:\d+(?::\d+)?$/, '').replace(/^\.\//, ''))
    .filter((path) => path.length > 0 && Object.prototype.hasOwnProperty.call(tree, path));
}

/** The `scripts` block of the package.json files next to the Dockerfile and at the root: what `npm start` runs. */
function packageScripts(tree: FileTree, dockerfile: string | undefined): PackFile[] {
  const directory = dockerfile?.includes('/') ? dockerfile.slice(0, dockerfile.lastIndexOf('/') + 1) : '';
  return [...new Set([`${directory}package.json`, 'package.json'])].flatMap((path) => {
    const lines = (tree[path] ?? '').split(/\r?\n/);
    const start = lines.findIndex((line) => line.includes('"scripts"'));
    if (start === -1) return [];
    const end = lines.findIndex((line, index) => index > start && /^\s*}/.test(line));
    return window(path, tree[path] ?? '', start + 1, Math.min(end === -1 ? start + 40 : end + 1, start + 40), 3_000) ?? [];
  });
}

function questionWindows(tree: FileTree, item: OpenItem, startPath: ReadonlySet<string>, dockerfile: string | undefined): PackFile[] {
  if (item.kind === 'blocker') {
    const named = namedPaths(item.reason, tree).filter((path) => !isExcludedPath(path));
    return hitWindows(tree, blockerSearch(item), RANKS['blocker']!, named, startPath, MAX_QUESTION_CHARS);
  }
  if (item.fact === 'dockerfile') {
    return listDockerfileCandidates(tree)
      .slice(0, 4)
      .flatMap((path) => window(path, tree[path] ?? '', 1, 60, MAX_QUESTION_CHARS / 4) ?? []);
  }
  if (item.fact === 'repositoryKind') {
    // The packaging lines of the shallowest manifests, then the server entrypoints the code has.
    const manifests = Object.keys(tree)
      .filter((path) => PACKAGE_MANIFEST.test(path) && isProductionFile(path))
      .sort((a, b) => a.split('/').length - b.split('/').length || a.localeCompare(b))
      .slice(0, 6);
    const packaging = hitWindows(Object.fromEntries(manifests.map((path) => [path, tree[path] ?? ''])), PACKAGING, (_path, line) => (PACKAGE_MARKER.test(line) ? 0 : 1), manifests, startPath, MAX_QUESTION_CHARS / 2);
    // The root README often says what the repository is (a database server, a broker): its first role
    // line in the introduction and the lines after it (badges above it would use the budget), else its top.
    const readme = Object.keys(tree).find((path) => ROOT_README.test(path));
    const role = readme === undefined ? -1 : (tree[readme] ?? '').split(/\r?\n/).slice(0, 60).findIndex((line) => DATASTORE_ROLE.test(line));
    const introFile = readme === undefined ? null : window(readme, tree[readme] ?? '', role === -1 ? 1 : role, role === -1 ? 40 : role + 1 + WINDOW_RADIUS, MAX_README_CHARS);
    const intro = introFile === null ? [] : [introFile];
    const skip = new Set([...startPath, ...manifests]);
    const used = [...packaging, ...intro].reduce((sum, file) => sum + size(file), 0);
    return [...packaging, ...intro, ...hitWindows(tree, FACT_SEARCH['repositoryKind']!, RANKS['repositoryKind']!, [], skip, MAX_QUESTION_CHARS - used)];
  }
  const scripts = item.fact === 'startCommand' || item.fact === 'migration' ? packageScripts(tree, dockerfile) : [];
  const procfiles = Object.keys(tree).filter((path) => /(?:^|\/)Procfile$/.test(path) && path.split('/').length <= 2);
  const budget = MAX_QUESTION_CHARS - scripts.reduce((sum, file) => sum + size(file), 0);
  const skip = new Set([...startPath, ...scripts.map((file) => file.path)]);
  return [...scripts, ...hitWindows(tree, FACT_SEARCH[item.fact]!, RANKS[item.fact]!, procfiles, skip, budget)];
}

/** Repository files the AI may read that the rules tree does not hold, per Analysis. */
export const MAX_EVIDENCE_FILES = 40;
const MAX_EVIDENCE_FILES_PER_QUESTION = 20;
/** Source files of every runtime the image can start (the rules tree reads only some of them). */
const EVIDENCE_SOURCE = /\.(?:cs|java|kt|scala|ex|exs|php|rs|ts|js|mjs|cjs|py|rb|go)$/i;
/** The files where an app boots: its main file, its startup class, its runtime configuration. */
const BOOT_FILE =
  /(?:^|\/)(?:Program\.cs|\w*Startup\.cs|\w*Application\.(?:java|kt)|Main\.(?:java|kt)|main\.(?:rs|go|py|ts|js)|(?:settings|config)\.rs|application\.ex|release(?:_?tasks)?\.ex|(?:runtime|prod|config)\.exs|index\.php|bootstrap\.php|Kernel\.php|appsettings(?:\.Production)?\.json|(?:server|app)\.\w+)$/i;
/** File names that hold what each question asks about. */
const EVIDENCE_NAME: Record<string, RegExp> = {
  migration: /migrat\w*(?:manager|runner|service|startup|task|extensions?|helper|or)\.\w+$|(?:database|db)(?:manager|context|initiali[sz]er|setup|migrator|migrations?)\.\w+$|release_?tasks\.\w+$|install(?:er|ation)?(?:manager|service)?\.\w+$|schema\.\w+$|worker\.\w+$/i,
  healthPath: /(?:health|status|ping|controller|routes?|router|endpoints?)[^/]*$/i,
  blocker: /(?:config|settings|configuration|storage|filesystem|paths?|options|database|db|data|env)[^/]*$/i,
  databaseVariable: /(?:config|settings|configuration|options|database|db|repo|env)[^/]*$/i,
};

/**
 * The repository files the evidence windows need beyond the rules tree: boot
 * code and the files named after each open question, in the languages the rules
 * fetch does not read (C#, Java, Kotlin, Elixir, PHP, Rust) or that the file cap
 * left out. Only production files; empty without the full path list or an open
 * item. The caller fetches them for the AI pack only: the rules never see them.
 */
export function evidenceFileRequests(tree: FileTree, analysis: AnalysisResult): string[] {
  const paths = (tree as FileTree & { [TREE_PATHS]?: readonly string[] })[TREE_PATHS];
  const items = collectOpenItems(tree, analysis);
  if (paths === undefined || items.length === 0) return [];
  const missing = paths.filter((path) => !Object.prototype.hasOwnProperty.call(tree, path) && isProductionFile(path) && !BROWSER_FILE.test(path));
  const byDepth = (a: string, b: string) => a.split('/').length - b.split('/').length || a.localeCompare(b);
  const requested = new Set<string>();
  const readme = paths.filter((path) => ROOT_README.test(path)).sort((a, b) => a.length - b.length)[0];
  if (readme !== undefined && items.some((item) => item.kind === 'fact' && item.fact === 'repositoryKind')) requested.add(readme);
  for (const item of items) {
    const name = item.kind === 'blocker' ? EVIDENCE_NAME['blocker'] : item.fact === 'dockerfile' ? undefined : EVIDENCE_NAME[item.fact];
    const boot = missing.filter((path) => BOOT_FILE.test(path) && (EVIDENCE_SOURCE.test(path) || path.endsWith('.json'))).sort(byDepth);
    // A numbered file is one migration, not the code that runs them.
    const named = name === undefined ? [] : missing.filter((path) => EVIDENCE_SOURCE.test(path) && name.test(path) && !/(?:^|\/)\d[^/]*$/.test(path) && !boot.includes(path)).sort(byDepth);
    for (const path of [...boot.slice(0, MAX_EVIDENCE_FILES_PER_QUESTION / 2), ...named].slice(0, MAX_EVIDENCE_FILES_PER_QUESTION)) requested.add(path);
  }
  return [...requested].slice(0, MAX_EVIDENCE_FILES);
}

/** Build the pack: the shared start path, then one window set per open question, inside `MAX_PACK_CHARS`. */
export function buildEvidencePack(tree: FileTree, analysis: AnalysisResult): EvidencePack {
  const selected = typeof analysis.metadata['dockerfilePath'] === 'string' ? analysis.metadata['dockerfilePath'] : listDockerfileCandidates(tree)[0];
  const startPath: PackFile[] = [];
  let remaining = MAX_START_PATH_CHARS;
  for (const path of selected === undefined ? [] : [selected, ...startScripts(selected, tree)]) {
    if (isExcludedPath(path) || remaining < 300) continue;
    const file = window(path, tree[path] ?? '', 1, Number.MAX_SAFE_INTEGER, remaining);
    if (file === null) continue;
    startPath.push(file);
    remaining -= size(file);
  }
  const shown = new Set(startPath.map((file) => file.path));

  const questions: Question[] = [];
  let packRemaining = MAX_PACK_CHARS - (MAX_START_PATH_CHARS - remaining);
  for (const [index, item] of collectOpenItems(tree, analysis).entries()) {
    const windows: PackFile[] = [];
    for (const file of questionWindows(tree, item, shown, selected)) {
      if (size(file) > packRemaining) break;
      windows.push(file);
      packRemaining -= size(file);
    }
    questions.push({ ...item, id: `q${index + 1}`, windows });
  }

  const listed = Object.keys(tree)
    .filter((path) => !VENDORED.test(path))
    .sort();
  return { questions, startPath, bindingContract: bindingContractOf(analysis), paths: listed.slice(0, MAX_LISTED_PATHS), totalPaths: listed.length };
}

/** Every window of the pack: the start path and the windows of each question. */
export function packFiles(pack: EvidencePack): PackFile[] {
  return [...pack.startPath, ...pack.questions.flatMap((question) => question.windows)];
}

export function renderFile(file: PackFile): string[] {
  return [`<<<FILE ${file.path} (lines ${file.start}-${file.start + file.lines.length - 1})`, ...file.lines.map((line, index) => `${file.start + index}| ${line}`), 'FILE>>>'];
}

function questionText(question: Question): string {
  if (question.kind === 'fact' && question.fact === 'repositoryKind') {
    return `${question.id} (kind "fact", fact "repositoryKind"): is this repository an application that serves HTTP, a datastore server that other applications connect to, or a library, framework, SDK or CLI that others install?`;
  }
  if (question.kind === 'fact') return `${question.id} (kind "fact", fact "${question.fact}"): what is the ${question.fact}?`;
  const subject =
    question.category === 'datastore'
      ? 'Does the production app need this datastore?'
      : question.category === 'local_state'
        ? 'Does the production app keep durable data (data that must survive a new container) on this local path?'
        : question.category === 'declared_service'
          ? 'Does the production app need any of these services at runtime?'
          : 'Does the web app need the other application service(s) to start and to serve its main function?';
  return `${question.id} (kind "blocker", ${question.category.replace('_', ' ')}): the scanner found: ${question.reason} ${subject}`;
}

/** The pack as prompt text: the binding contract, the start path, then each question with its windows. */
export function renderEvidencePack(pack: EvidencePack): string {
  const parts: string[] = [
    '## Deployz binding contract (JSON)',
    'The environment variables Deployz sets: always; for this repository; and the standard names it sets when it provisions a database, Redis or S3 storage.',
    JSON.stringify(pack.bindingContract, null, 1),
    '',
    `## Repository paths (${pack.paths.length} of ${pack.totalPaths})`,
    pack.paths.join('\n'),
    '',
    '## Start path (untrusted data; each line starts with its line number)',
    ...pack.startPath.flatMap(renderFile),
  ];
  for (const question of pack.questions) {
    parts.push('', `## Question ${questionText(question)}`, ...(question.windows.length > 0 ? question.windows.flatMap(renderFile) : ['(no window: answer from the start path, or "required" / "unknown")']));
  }
  return parts.join('\n');
}
